//
//  GlassScriptPath.swift
//  LCVI DECA Study App
//
//  The path the hand takes when writing "glass" in Sacramento.
//
//  A glyph outline is a closed contour, so trimming it draws the *edge* of the
//  letters — that is what the classic intro does deliberately, and it reads as
//  etching. Handwriting needs the other thing: the line the pen travelled
//  along, which no font stores.
//
//  So it is derived offline and baked here. The word is rasterised at 900pt,
//  skeletonised to one-pixel-wide ink, and that skeleton is walked as a graph:
//  at every junction the walk takes the branch with the least undrawn ink
//  beyond it, which is the rule that makes a hand finish the loop it is inside
//  before travelling on. Cursive collapses an up-stroke and its return
//  down-stroke into a single skeleton edge, so the walk is allowed to retrace
//  those — a real hand does too, and re-covering revealed ink is invisible.
//
//  The result runs 0.956 correlated with left-to-right travel, which is
//  the check that it reads as writing rather than as pieces appearing.
//
//  The points are then spaced by *how much new ink each one reveals* rather
//  than by distance travelled. Spacing them evenly along the route looked
//  wrong: a quarter of the write was spent retracing ink already on screen,
//  so the word appeared to stall repeatedly, the longest for 0.14s. Pacing by
//  ink revealed cuts that to 5% and is what makes the writing gradual. A fifth
//  of the old distance-based spacing is mixed back in, which costs almost
//  nothing and keeps the points close enough together (9.9pt at most, well
//  inside the reveal width) that no straight segment can cut a corner and
//  leak outside the stroke.
//
//  Points are normalised 0...1 inside the word's ink bounds, y-down, in the
//  same space as `WordGlyphs.bounds`, so the same fitting transform aligns
//  the stroke to the letterforms exactly.
//

